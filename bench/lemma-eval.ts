/**
 * Phase 4b offline evaluation against UD gold lemmas (CC BY-SA, evaluation only).
 *
 *     node bench/lemma-eval.ts --baseline [--split all]   # headroom: where fa-full misses the target, and why
 *     node bench/lemma-eval.ts --configs lm-tree,lm-list --split dev
 *
 * Unit: UD word tokens (and distinct types), each with its target (bench/lib/lemma.ts).
 * Per config, against fa-full: term accuracy, and how many tokens it **fixes**
 * (fa-full missed the target, the config hits it) and **breaks** (fa-full hit it, the
 * config does not). On residual examples (fa-full misses) the fixed share is the
 * coverage; on the others (fa-full already right, the model should defer) the broken
 * share is the false-fire rate, the precision proxy. Per treebank and UPOS, and for
 * words seen vs unseen in the config's training set when it reports one.
 *
 * `--split` picks the UD files: dev for tuning, test once at the end.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { configByName } from "./configs.ts";
import { cause, udExamples, type UdExample } from "./lib/lemma.ts";
import { TREEBANKS } from "./lib/ud.ts";

const { values } = parseArgs({
  options: {
    baseline: { type: "boolean", default: false },
    configs: { type: "string", default: "" },
    split: { type: "string", default: "dev" },
    name: { type: "string" },
    examples: { type: "string", default: "50" },
  },
});
const splits = values.split === "all" ? (["train", "dev", "test"] as const) : ([values.split] as ["dev"] | ["test"] | ["train"]);
const examples = udExamples(splits);
const lines: string[] = [];
const out = (s = "") => lines.push(s);
const pct = (a: number, b: number) => (b ? (100 * a / b).toFixed(1) : "–");
const k = (n: number) => n.toLocaleString("en");
const POS = ["NOUN", "ADJ", "VERB", "ADV", "PROPN", "other"];
const posOf = (e: UdExample) => (POS.includes(e.upos) ? e.upos : "other");

if (values.baseline) {
  out(`# Lemma model headroom: where fa-full misses the target (UD ${values.split})`);
  out();
  out("Generated by `node bench/lemma-eval.ts --baseline --split " + values.split + "`. Target: a verb's (ن)+past stem (PerDT only), else the term fa-full gives the gold lemma. Tokens (types in brackets).");
  out();
  for (const bank of TREEBANKS) {
    const list = examples.filter((e) => e.bank === bank);
    out(`## ${bank}`);
    out();
    out("| UPOS | tokens | fa-full misses | % |");
    out("|---|---:|---:|---:|");
    for (const pos of POS) {
      const xs = list.filter((e) => posOf(e) === pos);
      const tok = xs.reduce((s, e) => s + e.count, 0);
      const miss = xs.filter((e) => e.base !== e.target);
      const mt = miss.reduce((s, e) => s + e.count, 0);
      out(`| ${pos} | ${k(tok)} (${k(xs.length)}) | ${k(mt)} (${k(miss.length)}) | ${pct(mt, tok)} |`);
    }
    out();
    out("Misses by cause (tokens, types) and UPOS:");
    out();
    const causes = new Map<string, Map<string, [number, number]>>();
    for (const e of list) {
      if (e.base === e.target) continue;
      const c = cause(e);
      const m = causes.get(c) ?? new Map();
      const x = m.get(posOf(e)) ?? [0, 0];
      x[0] += e.count; x[1]++;
      m.set(posOf(e), x);
      causes.set(c, m);
    }
    out(`| cause | ${POS.join(" | ")} |`);
    out(`|---|${POS.map(() => "---:").join("|")}|`);
    const total = (m: Map<string, [number, number]>) => [...m.values()].reduce((s, x) => s + x[0], 0);
    for (const [c, m] of [...causes].sort((a, b) => total(b[1]) - total(a[1]))) {
      out(`| ${c} | ${POS.map((p) => { const x = m.get(p); return x ? `${k(x[0])} (${k(x[1])})` : "–"; }).join(" | ")} |`);
    }
    out();
    out(`Most frequent misses (${values.examples}): form → fa-full's term, target (lemma)`);
    out();
    const top = list.filter((e) => e.base !== e.target).sort((a, b) => b.count - a.count).slice(0, Number(values.examples));
    out(top.map((e) => `«${e.token}» → ${e.base}, want ${e.target} (${e.lemma}, ${e.upos}, ${e.count})`).join(" · "));
    out();
  }
  write(values.name ?? `lemma-baseline-${values.split}`);
}

for (const name of values.configs.split(",").filter(Boolean)) {
  const config = configByName(name);
  const term = (t: string) => config.analyzer!.analyze(t, "query").join(" ");
  const seen = (config as { lemmaSeen?: (w: string) => boolean }).lemmaSeen;
  out(`## ${name} (UD ${values.split})`);
  out();
  out("Tokens (types). Coverage = fixed / fa-full's misses; false-fire = broken / fa-full's hits.");
  out();
  out("| treebank | UPOS | tokens | fa-full right % | right % | fixed | broken | coverage % | false-fire % |");
  out("|---|---|---:|---:|---:|---:|---:|---:|---:|");
  const wrong: { e: UdExample; t: string }[] = [], missed: { e: UdExample; t: string }[] = [];
  for (const bank of TREEBANKS) {
    for (const pos of [...POS, "all"]) {
      const xs = examples.filter((e) => e.bank === bank && (pos === "all" || posOf(e) === pos));
      let tok = 0, baseRight = 0, right = 0, fixed = 0, broken = 0, miss = 0, hit = 0;
      for (const e of xs) {
        const t = term(e.token);
        tok += e.count;
        const b = e.base === e.target, m = t === e.target;
        if (b) { baseRight += e.count; hit += e.count; } else miss += e.count;
        if (m) right += e.count;
        if (!b && m) fixed += e.count;
        if (b && !m) { broken += e.count; if (pos === "all") wrong.push({ e, t }); }
        if (!b && !m && pos === "all") missed.push({ e, t });
      }
      out(`| ${bank} | ${pos} | ${k(tok)} | ${pct(baseRight, tok)} | ${pct(right, tok)} | ${k(fixed)} | ${k(broken)} | ${pct(fixed, miss)} | ${pct(broken, hit)} |`);
    }
  }
  out();
  if (seen) {
    out("Seen vs unseen words (in the model's training set):");
    out();
    out("| | tokens | fixed | broken | coverage % | false-fire % |");
    out("|---|---:|---:|---:|---:|---:|");
    for (const s of [true, false]) {
      let tok = 0, fixed = 0, broken = 0, miss = 0, hit = 0;
      for (const e of examples.filter((x) => seen(x.word) === s)) {
        const t = term(e.token), b = e.base === e.target, m = t === e.target;
        tok += e.count;
        if (b) hit += e.count; else miss += e.count;
        if (!b && m) fixed += e.count;
        if (b && !m) broken += e.count;
      }
      out(`| ${s ? "seen" : "unseen"} | ${k(tok)} | ${k(fixed)} | ${k(broken)} | ${pct(fixed, miss)} | ${pct(broken, hit)} |`);
    }
    out();
  }
  const n = Number(values.examples);
  out(`Most frequent wrong fires (${n}): form → term, want (lemma)`);
  out();
  out(wrong.sort((a, b) => b.e.count - a.e.count).slice(0, n).map(({ e, t }) => `«${e.token}» → ${t}, want ${e.target} (${e.upos}, ${e.count})`).join(" · "));
  out();
  out(`Most frequent misses (${n}):`);
  out();
  out(missed.sort((a, b) => b.e.count - a.e.count).slice(0, n).map(({ e, t }) => `«${e.token}» → ${t}, want ${e.target} (${e.upos}, ${e.count})`).join(" · "));
  out();
}
if (values.configs) write(values.name ?? `lemma-eval-${values.split}`);

function write(name: string) {
  mkdirSync(new URL("results/", import.meta.url), { recursive: true });
  writeFileSync(new URL(`results/${name}.md`, import.meta.url), lines.join("\n") + "\n");
  console.log(lines.filter((l) => l.startsWith("|") || l.startsWith("#")).join("\n"));
  console.log(`wrote bench/results/${name}.md`);
  lines.length = 0;
}
